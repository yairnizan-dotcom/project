import streamlit as st

# כותרות ורמות היררכיה לעיצוב מבנה העמוד
st.title("🎬 CinePredict AI")
st.header("מערכת בינה מלאכותית לחיזוי והמלצות סרטים")
st.subheader("הזינו את פרטי הסרט כדי לקבל ניתוח מהמודל")

# קליטת קלט מהמשתמש (תיבת טקסט רגילה ותיבת טקסט רחבה)
movie_name = st.text_input("מה שם הסרט?")
user_prompt = st.text_area("הזינו את תקציר עלילת הסרט (ז'אנר, שחקנים וסיפור):")

# בדיקה האם המשתמש הקליד טקסט בתקציר
if user_prompt:
    # שלב החיזוי (סימולציה של תשובת המודל לפי הדוגמה)
    response = "הסרט בעל פוטנציאל הצלחה גבוה מאוד! המודל צופה ציון של 8.5 ותגובות חיוביות מהקהל."
    
    st.subheader("תוצאת החיזוי:")
    
    # הצגת התוצאה באמצעות הפקודה הכללית
    st.write(response)
    
    # רקע צבעוני לטקסט - להבלטת הודעת הצלחה ומידע חשוב
    st.success("הניתוח הושלם בהצלחה!")
    st.info("המלצת המודל: מומלץ להפיץ את הסרט במהלך חופשת הקיץ.")

